def main(path="translations/hydra64_en.ts"):
    tree = ET.parse(path)
    missing = []
    for msg in tree.getroot().iter("message"):
        src = msg.find("source").text
        tr = msg.find("translation")
        comment = msg.find("comment")
        value = EN.get((src, comment.text)) if comment is not None else None
        if value is None:
            value = EN.get(src)
        if value is None:
            missing.append(src)
            continue
        tr.attrib.pop("type", None)  # no longer "unfinished"
        for child in list(tr):
            tr.remove(child)
        if msg.get("numerus") == "yes":
            forms = value if isinstance(value, tuple) else (value, value)
            tr.text = None
            for f in forms:
                ET.SubElement(tr, "numerusform").text = f
        else:
            tr.text = value[1] if isinstance(value, tuple) else value
    tree.write(path, encoding="utf-8", xml_declaration=True)
    for m in missing:
        print("non traduit :", repr(m))
    print(f"{path} : {len(missing)} texte(s) sans traduction")
    return 1 if missing else 0

if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:]))
