#!/usr/bin/env python3
"""Rebuilds src/ui/baseicons.inc: the icons offered for databases (right-click → Change the icon).

The drawings come from Lucide (https://lucide.dev, ISC licence), npm package "lucide-static":
    python3 tools/make_base_icons.py path/to/lucide-static/icons

To add an icon: its Lucide name in the wanted theme below, then run this script again.
The identifier saved in the settings is this name: do not rename an icon already offered.
"""
import os
import re
import sys

THEMES = [
    ("Échecs", "chess-king chess-queen chess-rook chess-bishop chess-knight chess-pawn crown swords sword shield castle grid-3x3 puzzle brain target crosshair hourglass timer"),
    ("Étude", "book book-open book-marked library graduation-cap school lightbulb notebook-pen pencil bookmark microscope telescope compass map route signpost git-branch network"),
    ("Joueurs", "user users user-round user-star baby contact id-card handshake glasses bot cpu monitor laptop smartphone globe mail wifi"),
    ("Tournois", "trophy medal award flag flag-triangle-right calendar calendar-days ticket landmark building-2 tent plane map-pin zap rabbit turtle flame rocket"),
    ("Collections", "database archive box folder folder-open inbox hard-drive save clipboard file-text files tag tags pin paperclip star heart gem sparkles thumbs-up eye download cloud"),
    ("Symboles", "sun moon mountain tree-pine leaf flower snowflake anchor key lock skull ghost cat dog bird fish bug coffee music camera palette dice-5 club spade diamond"),
]


NUMBER = re.compile(r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?")


def spaced(d):
    """Path data rewritten with one number per argument, separated by spaces.

    Lucide compacts arcs ("a.65.65 0 01-1.131.295": the two flags glued to the next number),
    which not every SVG reader parses; here each argument is isolated."""
    out, i, cmd = [], 0, None
    while i < len(d):
        c = d[i]
        if c in " ,\t\n":
            i += 1
        elif c.isalpha():
            cmd, taken = c, 0
            out.append(c)
            i += 1
        elif cmd in "aA" and taken % 7 in (3, 4):  # flags of an arc: a single character
            if c not in "01":
                sys.exit(f"drapeau d'arc inattendu : {d}")
            out.append(c)
            taken += 1
            i += 1
        else:
            m = NUMBER.match(d, i)
            if not m:
                sys.exit(f"unreadable path: {d}")
            out.append(m.group(0))
            taken += 1
            i = m.end()
    return " ".join(out)


def body(path):
    svg = open(path, encoding="utf-8").read()
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    inner = re.sub(r"\s+", " ", inner).strip().replace("> <", "><").replace(" />", "/>")
    inner = re.sub(r' d="([^"]*)"', lambda m: f' d="{spaced(m.group(1))}"', inner)
    if ')"' in inner or not re.fullmatch(r'(<(path|circle|rect|line|polyline|polygon|ellipse)( [a-z0-9-]+="[^"<>]*")*/>)+', inner):
        sys.exit(f"dessin inattendu : {path}")
    return inner


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = ["// File generated by tools/make_base_icons.py — do not edit by hand.",
           "// Drawings: Lucide (https://lucide.dev), ISC licence.",
           "// {identifier, theme number, 24×24 SVG line drawing}"]
    count = 0
    for theme, (name, icons) in enumerate(THEMES):
        out.append(f"// ---- {name}")
        for icon in icons.split():
            out.append(f'{{"{icon}", {theme}, R"({body(os.path.join(sys.argv[1], icon + ".svg"))})"}},')
            count += 1
    dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "ui", "baseicons.inc")
    open(dest, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"{count} icons, {len(THEMES)} themes → {os.path.normpath(dest)}")


if __name__ == "__main__":
    main()
