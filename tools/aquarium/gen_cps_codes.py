#!/usr/bin/env python3
"""Generates src/chess/aquarium_codes.inc from Aquarium's addonce1.dll file.

Usage: python3 tools/aquarium/gen_cps_codes.py path/to/addonce1.dll

addonce1.dll (© ChessOK) contains the code tables of the CPS packing of positions:
160,224 entries of 32 bits (code length on 5 bits, code on 27 bits), 87 % of them zero.
Only the ranges of non-zero entries are kept.
"""
import struct
import sys

data = open(sys.argv[1], 'rb').read()
assert len(data) == 640896, 'taille inattendue : ce n\'est pas addonce1.dll'
v = struct.unpack(f'<{len(data) // 4}I', data)
segments, values = [], []
i = 0
while i < len(v):
    if v[i] == 0:
        i += 1
        continue
    j = i
    while j < len(v) and v[j] != 0:
        j += 1
    segments.append((i, j - i))
    values.extend(v[i:j])
    i = j

out = ['// Generated by tools/aquarium/gen_cps_codes.py from Aquarium\'s addonce1.dll (© ChessOK):',
       '// code tables of the CPS packing of Aquarium / Chess Assistant trees.',
       f'// {len(v)} entries, {len(values)} of them non-zero, in {len(segments)} ranges.',
       '',
       f'constexpr uint32_t CodeTableEntries = {len(v)};',
       '',
       '// Ranges of non-zero entries: {first index, count}',
       f'constexpr uint32_t CodeSegments[{len(segments)}][2] = {{']
for k in range(0, len(segments), 8):
    out.append('    ' + ' '.join(f'{{{a}, {n}}},' for a, n in segments[k:k + 8]))
out += ['};', '', '// Values of the non-zero entries, range after range',
        f'constexpr uint32_t CodeValues[{len(values)}] = {{']
for k in range(0, len(values), 8):
    out.append('    ' + ' '.join(f'0x{x:08x},' for x in values[k:k + 8]))
out += ['};', '']
open('src/chess/aquarium_codes.inc', 'w').write('\n'.join(out))
print(f'{len(segments)} plages, {len(values)} valeurs')
